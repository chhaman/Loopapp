// Single source of truth for HTTP security headers.
// Used by next.config.ts (pages, dev server) and written to public/_headers
// (Cloudflare static assets) by scripts/build-miniapps.mjs.

/** Miniapp documents: no network, no storage, no framing outside Loopapp (RNF-005). */
export const miniappHeaders = {
  "Content-Security-Policy": [
    "default-src 'none'",
    "script-src 'unsafe-inline'",
    "style-src 'unsafe-inline'",
    "img-src data: blob:",
    "font-src data:",
    "media-src data: blob:",
    "connect-src 'none'",
    "form-action 'none'",
    "base-uri 'none'",
    "frame-ancestors 'self'",
    "sandbox allow-scripts",
  ].join("; "),
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "no-referrer",
  "Cross-Origin-Resource-Policy": "same-origin",
  "Permissions-Policy":
    "camera=(), microphone=(), geolocation=(), payment=(), usb=(), clipboard-read=(), clipboard-write=(), display-capture=(), fullscreen=()",
};

/** Host application pages. */
export const appHeaders = {
  "Content-Security-Policy": "frame-ancestors 'none'; base-uri 'self'; form-action 'self'; object-src 'none'",
  "X-Frame-Options": "DENY",
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=(), usb=()",
};

const toList = (headers) => Object.entries(headers).map(([key, value]) => ({ key, value }));

export function nextHeaders() {
  return [
    { source: "/miniapps/:path*", headers: toList(miniappHeaders) },
    { source: "/((?!miniapps/).*)", headers: toList(appHeaders) },
  ];
}

export function cloudflareHeadersFile() {
  const block = (path, headers) =>
    [path, ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`)].join("\n");
  return [
    "# Generated by scripts/build-miniapps.mjs from security-headers.mjs — do not edit.\n# https://developers.cloudflare.com/workers/static-assets/headers/",
    block("/miniapps/*", miniappHeaders),
    block("/_next/static/*", { "Cache-Control": "public, max-age=31536000, immutable" }),
    "",
  ].join("\n\n");
}
